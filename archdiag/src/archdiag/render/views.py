"""ArchModel v2 view → Mermaid. Labels go through the same escaping as the v1 compiler."""

from __future__ import annotations

from collections import defaultdict

from archdiag.model.schema_v2 import ArchModelV2, NodeV2, View
from archdiag.render.mermaid import escape_label

HEAVY_WEIGHT = 10
_DIRECTION = {"system": "LR", "component": "TD", "layer": "TD", "class": "BT"}


def _shape(node: NodeV2) -> str:
    label = escape_label(node.label)
    if node.level == "external":
        return f'(["{label}"])'
    if node.level == "actor":
        return f'{{{{"{label}"}}}}'
    if node.level in ("layer", "system"):
        return f'[["{label}"]]'
    if node.kind == "interface":
        return f'[/"{escape_label("«interface» " + node.label)}"/]'
    return f'["{label}"]'


def safe_view_file(view_id: str) -> str:
    return view_id.replace("/", "__") + ".mmd"


def compile_view(model: ArchModelV2, view: View) -> str:
    nodes = {n.id: n for n in model.nodes}
    edges = {e.id: e for e in model.edges}
    violating = {v.edge_id for v in model.violations if v.edge_id}
    groups = {g.id: g for g in model.groups}
    lines = [
        f"%% Generated by archdiag: view {view.id}. Edit the code or archdiag.toml, not this file.",
        f"flowchart {_DIRECTION.get(view.level, 'TD')}",
    ]
    members = [nodes[i] for i in view.node_ids if i in nodes]
    grouped: dict[str | None, list[NodeV2]] = defaultdict(list)
    use_groups = view.level == "component"
    for node in members:
        grouped[node.group if use_groups and node.group in groups else None].append(node)
    for group_id, group_nodes in grouped.items():
        if group_id is None:
            continue
        lines.append(f'  subgraph g_{group_id}["{escape_label(groups[group_id].label)}"]')
        lines.extend(f"    n_{n.id}{_shape(n)}" for n in group_nodes)
        lines.append("  end")
    lines.extend(f"  n_{n.id}{_shape(n)}" for n in grouped.get(None, []))

    present = {n.id for n in members}
    red: list[int] = []
    index = 0
    for edge_id in view.edge_ids:
        edge = edges.get(edge_id)
        if edge is None or edge.source not in present or edge.target not in present:
            continue
        if edge.confidence == "low":
            arrow = "-.->"
        elif edge.weight >= HEAVY_WEIGHT:
            arrow = "==>"
        else:
            arrow = "-->"
        text = edge.label or (str(edge.weight) if edge.kind in ("depends", "uses") else edge.kind)
        lines.append(f'  n_{edge.source} {arrow}|"{escape_label(text, 40)}"| n_{edge.target}')
        if edge.id in violating:
            red.append(index)
        index += 1
    if red:
        lines.append(f"  linkStyle {','.join(map(str, red))} stroke:#d1242f,stroke-width:3px")
    return "\n".join(lines) + "\n"
