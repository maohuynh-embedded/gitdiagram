"""Deterministic ArchModel → Mermaid compiler.

Every label is escaped into Mermaid entity codes, and no click/href directive is ever emitted:
node interaction is wired up by the web UI from the validated model instead.
"""

from __future__ import annotations

from collections import defaultdict

from archdiag.model.schema import ArchModel, Group, Node

_MAX_LABEL = 80
_MAX_EDGE_LABEL = 40
_SAFE_PUNCTUATION = frozenset(" _-./:,()+*=?!'@~")


def escape_label(text: str, max_len: int = _MAX_LABEL) -> str:
    cleaned = "".join(ch if ch.isprintable() else " " for ch in text)
    cleaned = " ".join(cleaned.split())
    if len(cleaned) > max_len:
        cleaned = cleaned[: max_len - 1] + "…"
    return "".join(
        ch if ch.isalnum() or ch in _SAFE_PUNCTUATION or ch == "…" else f"#{ord(ch)};"
        for ch in cleaned
    )


def compile_mermaid(model: ArchModel) -> str:
    child_groups: dict[str | None, list[Group]] = defaultdict(list)
    for group in model.groups:
        child_groups[group.parent].append(group)
    nodes_in: dict[str | None, list[Node]] = defaultdict(list)
    for node in model.nodes:
        nodes_in[node.group].append(node)

    def has_content(group_id: str) -> bool:
        return bool(nodes_in[group_id]) or any(
            has_content(child.id) for child in child_groups[group_id]
        )

    lines = ["%% Generated by archdiag. Edit model.json, not this file.", "flowchart TD"]

    def emit_group(group: Group, depth: int) -> None:
        indent = "  " * depth
        lines.append(f'{indent}subgraph g_{group.id}["{escape_label(group.label)}"]')
        for child in child_groups[group.id]:
            if has_content(child.id):
                emit_group(child, depth + 1)
        for node in nodes_in[group.id]:
            lines.append(f'{indent}  n_{node.id}["{escape_label(node.label)}"]')
        lines.append(f"{indent}end")

    for group in child_groups[None]:
        if has_content(group.id):
            emit_group(group, 1)
    for node in nodes_in[None]:
        lines.append(f'  n_{node.id}["{escape_label(node.label)}"]')
    for edge in model.edges:
        if edge.label:
            label = escape_label(edge.label, _MAX_EDGE_LABEL)
            lines.append(f'  n_{edge.source} -->|"{label}"| n_{edge.target}')
        else:
            lines.append(f"  n_{edge.source} --> n_{edge.target}")
    return "\n".join(lines) + "\n"
